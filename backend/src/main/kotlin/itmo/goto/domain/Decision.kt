package itmo.goto.domain

/**
 * Итог запроса к [Meeting]: [Accepted] или [Refused].
 *
 * Оба итога несут встречу для сохранения, потому что каждый запрос сначала актуализирует состояние, и этот
 * переход должен сохраниться, даже когда сам запрос отклонён.
 */
interface Decision {
    /**
     * Превращает итог в значение, которое выбирает вызывающий код.
     *
     * @param accepted получает встречу для сохранения, когда запрос принят
     * @param refused получает актуальную встречу для сохранения и причину, когда запрос отклонён
     */
    fun <R> fold(accepted: (Meeting) -> R, refused: (Meeting, Refusal) -> R): R
}
