package itmo.goto.domain

/**
 * Пять состояний события из контракта.
 *
 * Между ними встречу переводят только срок регистрации и время окончания; набор минимума или максимума
 * состояние не меняет.
 */
enum class State {
    /** Регистрация открыта до срока. */
    RECRUITING,

    /** Срок наступил при набранном минимуме. */
    REGISTRATION_CLOSED,

    /** Срок наступил. */
    CANCELLED_BY_SYSTEM,

    /** Организатор отменил встречу. */
    CANCELLED_BY_ORGANIZER,

    /** Наступило время окончания встречи с закрытой регистрацией. */
    FINISHED,
}
