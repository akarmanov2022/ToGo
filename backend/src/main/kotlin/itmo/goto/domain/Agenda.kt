package itmo.goto.domain

import java.time.Instant

/**
 * Другие встречи, в которых участвует человек; они решают, может ли он взять на себя ещё одну.
 *
 * Нельзя участвовать в двух действующих встречах, начала которых отстоят меньше чем на три часа; отменённые
 * и завершённые встречи время не занимают.
 */
class Agenda(private val meetings: List<Meeting>) {
    /**
     * Сообщает, начинается ли встреча с расписанием [schedule] меньше чем через три часа от какой-либо действующей
     * встречи здесь, оценивая каждую по её состоянию на момент [now], а не по сохранённому.
     */
    fun conflicts(schedule: Schedule, now: Instant): Boolean = meetings.any { it.clashes(schedule, now) }
}
