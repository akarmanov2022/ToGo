package itmo.goto.domain

/**
 * Роли.
 */
enum class Role {
    /** Создал встречу, участвует в ней и единственный может её изменить или отменить. */
    ORGANIZER,

    /** Присоединился к встрече и может выйти, пока регистрация открыта. */
    PARTICIPANT,

    /** Не участвует во встрече и может присоединиться, пока регистрация открыта. */
    OUTSIDER,
}
